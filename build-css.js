// A source's text with Windows line endings made plain, so the same files
// give the same result, and the same fingerprint, on any computer.
function readSource(name) {
  return fs
    .readFileSync(path.join(SOURCE_DIR, name), "utf8")
    .replace(/\r\n/g, "\n");
}

// Point a source's relative url()s from precentor.css's folder instead of
// the source's own: url("fonts/x.woff2") in global/fonts.css becomes
// url("global/fonts/x.woff2"). Absolute and data: addresses are left.
function rewriteUrls(css, name) {
  return css.replace(/url\(\s*(["']?)([^"')]+)\1\s*\)/g, (match, quote, url) => {
    if (/^(\/|data:|https?:|#)/.test(url)) return match;
    const target = path.posix.join(path.posix.dirname(name), url);
    return `url(${quote}${target}${quote})`;
  });
}

// The fingerprint test_css.py checks: SHA-256 of the sources' plain text,
// in order, each after its name.
function fingerprint() {
  const hash = crypto.createHash("sha256");
  for (const name of SOURCES) hash.update(`${name}\n${readSource(name)}`);
  return hash.digest("hex");
}

function build() {
  const parts = SOURCES.map(
    (name) => `/* ---- ${name} ---- */\n${rewriteUrls(readSource(name), name)}`,
  );
  const header =
    `/**\n` +
    ` * AUTO-GENERATED by build-css.js from the files under static/src/.\n` +
    ` * Do not edit this file directly; edit a source file and build again.\n` +
    ` *\n` +
    ` * Sources, in cascade order:\n` +
    SOURCES.map((name) => ` *   ${name}\n`).join("") +
    ` *\n` +
    ` * Fingerprint: ${fingerprint()}\n` +
    ` */\n\n`;
  fs.writeFileSync(OUTPUT_PATH, header + parts.join("\n"), "utf8");
  console.log(
    `[build-css] wrote ${path.relative(__dirname, OUTPUT_PATH)} from ${SOURCES.length} files`,
  );
}

build();
