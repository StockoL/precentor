/**
 * ============================================================================
 * STYLESHEET BUILDER (build-css.js) for Precentor
 * ============================================================================
 * Joins the CSS source files under static/src/ into one stylesheet,
 * static/src/precentor.css, which is the only one base.html links. A page
 * then makes one request for all its CSS (about 19 KB compressed), and
 * the browser keeps it for every page after the first, where 46 separate
 * files meant 46 requests on every first visit.
 *
 * The source files stay separate, one block or composition each, and are
 * where all editing happens. DO NOT hand-edit precentor.css; edit a
 * source file, then:
 *
 *   node build-css.js
 *
 * Joining files in order behaves exactly like linking them in that order:
 * layers.css still declares the cascade layers first, every rule stays in
 * the layer its file puts it in, and the music list's print rules stay
 * outside any layer. The only change is to relative url()s (the web
 * fonts), which are rewritten to point from precentor.css's folder.
 *
 * The header records the sources and a fingerprint of them, and
 * precentor_project/test_css.py fails if a source has changed, been added
 * or gone without the file being built again.
 *
 * No npm dependencies required, only Node's built-in modules.
 * ============================================================================
 */

const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const SOURCE_DIR = path.join(__dirname, "static", "src");
const OUTPUT_PATH = path.join(SOURCE_DIR, "precentor.css");

// The cascade order, which was the order of the <link>s in base.html:
// layers first, then tokens and fonts, the reset and global styles,
// compositions, blocks and utilities.
